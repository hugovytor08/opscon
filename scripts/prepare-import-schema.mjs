import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const schema = JSON.parse(await readFile(new URL('docs/importacao/contrato-importacao.schema.json', root), 'utf8'));
await writeFile(new URL('app/import-schema.js', root), `// Generated by scripts/prepare-import-schema.mjs from the versioned draft contract.\nexport const importSchema = ${JSON.stringify(schema, null, 2)};\n`);
