import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Add a wrapper around the installed v2 validator; do not rewrite old snapshots
// or receipts. All previous allocation/ID/integrity/RLS checks remain active.
const bytes = await readFile(new URL('../supabase/migrations/202610150001_retroactive.sql', import.meta.url));
const source = bytes.toString('utf8').replace(/\r\n/g, '\n');
let rpc = source.slice(source.indexOf('create or replace function public.casa_commit_snapshot('), source.indexOf("insert into casa_private.schema_versions"));
rpc = rpc.replace("stored_schema = '2' and p_state->>'schemaVersion' <> '2'", "coalesce(stored_schema::int, 0) > (p_state->>'schemaVersion')::int").replace('Update client before changing version 2 data', 'Update client before changing newer data');
const sql = `-- Domain 3 / protocol 1. Apply after 202610150001, once.
-- Generated by scripts/prepare-benefit-migration.mjs.
-- Previous migration SHA-256: ${createHash('sha256').update(bytes).digest('hex')}
begin;
alter function casa_private.validate_snapshot(jsonb) rename to validate_snapshot_v2;
create function casa_private.validate_snapshot(s jsonb) returns void
language plpgsql set search_path = '' as $$
declare r jsonb; a jsonb; balance numeric; bank_total numeric := 0; benefit_total numeric := 0;
begin
  if s->'schemaVersion' in ('1'::jsonb, '2'::jsonb) then
    for r in select value from jsonb_array_elements(s->'accounts') loop
      if r ?| array['kind','monthlyCreditCents','creditDay'] then raise exception 'v3 account in legacy snapshot'; end if;
    end loop;
    for r in select value from jsonb_array_elements(s->'incomes') loop
      if r ? 'benefitPeriod' then raise exception 'v3 income in legacy snapshot'; end if;
    end loop;
    perform casa_private.validate_snapshot_v2(s);
    return;
  end if;
  if s->'schemaVersion' is distinct from '3'::jsonb then raise exception 'invalid schema'; end if;
  perform casa_private.validate_snapshot_v2(jsonb_set(s, '{schemaVersion}', '2'::jsonb));
  for a in select value from jsonb_array_elements(s->'accounts') loop
    if a->>'kind' is null or a->>'kind' not in ('bank','benefit') then raise exception 'invalid account kind'; end if;
    select (a->>'openingBalanceCents')::numeric
      + coalesce((select sum((i->>'amountCents')::numeric) from jsonb_array_elements(s->'incomes') i where i->>'accountId' = a->>'id' and i->>'balanceEffect' = 'apply'), 0)
      - coalesce((select sum((p->>'amountCents')::numeric) from jsonb_array_elements(s->'payments') p where p->>'accountId' = a->>'id' and p->>'balanceEffect' = 'apply'), 0)
      + coalesce((select sum((x->>'amountCents')::numeric) from jsonb_array_elements(s->'transfers') x where x->>'toAccountId' = a->>'id' and x->>'toBalanceEffect' = 'apply'), 0)
      - coalesce((select sum((x->>'amountCents')::numeric) from jsonb_array_elements(s->'transfers') x where x->>'fromAccountId' = a->>'id' and x->>'fromBalanceEffect' = 'apply'), 0) into balance;
    if a->>'kind' = 'bank' then
      bank_total := bank_total + balance;
      if a ?| array['monthlyCreditCents','creditDay'] then raise exception 'benefit policy on bank account'; end if;
    else
      if a->'monthlyCreditCents' is distinct from '69000'::jsonb or a->'creditDay' is distinct from '30'::jsonb
        or (a->>'openingBalanceCents')::numeric < 0 then raise exception 'invalid benefit policy or balance'; end if;
      benefit_total := benefit_total + balance;
      if balance < 0 then raise exception 'insufficient benefit'; end if;
      if exists(select 1 from jsonb_array_elements(s->'transfers') x where a->>'id' in (x->>'fromAccountId', x->>'toAccountId')) then raise exception 'bank transfer with benefit'; end if;
    end if;
  end loop;
  perform casa_private.integer_value(to_jsonb(bank_total), -9007199254740991);
  perform casa_private.integer_value(to_jsonb(benefit_total), 0);
  for r in select value from jsonb_array_elements(s->'incomes') loop
    select value into a from jsonb_array_elements(s->'accounts') where value->>'id' = r->>'accountId';
    if a->>'kind' = 'benefit' then
      if jsonb_typeof(r->'benefitPeriod') is distinct from 'string' or r->>'benefitPeriod' !~ '^[0-9]{4}-(0[1-9]|1[0-2])$' or left(r->>'benefitPeriod',4) = '0000' then raise exception 'invalid benefit competence'; end if;
      if (select count(*) from jsonb_array_elements(s->'incomes') i where i->>'accountId' = r->>'accountId' and i->>'benefitPeriod' = r->>'benefitPeriod') <> 1 then raise exception 'duplicate benefit competence'; end if;
    elsif r ? 'benefitPeriod' then raise exception 'benefit income without wallet'; end if;
  end loop;
exception when others then
  raise exception using errcode = 'CS400', message = 'Snapshot failed validation';
end $$;
`;
await writeFile(new URL('../supabase/migrations/202610150002_benefit.sql', import.meta.url), sql + rpc + "insert into casa_private.schema_versions(version, protocol) values ('202610150002', 1);\ncommit;\n");
console.log('Complemento alimentação gerado; migrações anteriores preservadas.');
