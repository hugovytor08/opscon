import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const source = new URL('docs/design/apartamento-real/', root);
const target = new URL('app/assets/apartamento-real/', root);
const data = JSON.parse(await readFile(new URL('areas-interativas.json', source), 'utf8'));
const svg = await readFile(new URL('casa-isometrica.svg', source), 'utf8');
if (/<script\b|<foreignObject\b|\son\w+\s*=|(?:href|src)\s*=/i.test(svg)) throw new Error('SVG deve ser autocontido e sem conteudo ativo.');
if (data.regions.length !== 8 || new Set(data.regions.map(region => region.id)).size !== 8) throw new Error('Regioes invalidas.');
const regions = data.regions.map(({ id, name, number, polygon, labelPosition }) => ({ id, name, number, polygon, labelPosition }));
await mkdir(target, { recursive: true });
await copyFile(new URL('casa-isometrica.svg', source), new URL('casa-isometrica.svg', target));
await writeFile(new URL('app/house-map-data.js', root), `// Generated by scripts/prepare-house-map.mjs; geometry remains estimated.\nexport const houseMap = ${JSON.stringify({ viewBox: data.viewBox, regions }, null, 2)};\n`);
console.log(`Mapa preparado: ${fileURLToPath(target)} (sem fotos/videos originais).`);
